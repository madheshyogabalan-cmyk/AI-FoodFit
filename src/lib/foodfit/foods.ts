export const foodById = (id: string) => FOODS.find((f) => f.id === id);

export function searchFoods(q: string): FoodItem[] {
  const s = q.trim().toLowerCase();
  if (!s) return [];
  return FOODS.filter((f) =>
    [f.name, f.nameTa, ...(f.aliases ?? [])].some((x) => x.toLowerCase().includes(s)),
  );
}

/** Parse things like "2 idli", "100g chicken breast", "3 eggs" */
export function parseQuery(q: string): { food: FoodItem; qty: number } | null {
  const s = q.trim().toLowerCase();
  const gram = s.match(/(\d+(?:\.\d+)?)\s*(?:g|gram|grams|gm)\b/);
  const count = s.match(/^(\d+(?:\.\d+)?)\s*(?:x\s*)?/);
  const words = s
    .replace(/(\d+(?:\.\d+)?)\s*(?:g|gram|grams|gm|x)?/g, " ")
    .replace(/[^a-z\u0B80-\u0BFF ]/g, " ")
    .trim();
  const candidates = words
    ? FOODS.filter((f) =>
        [f.name, f.nameTa, ...(f.aliases ?? [])].some((x) => {
          const xl = x.toLowerCase();
          return words.includes(xl) || xl.includes(words) || words.split(" ").includes(xl);
        }),
      )
    : [];
  const food = candidates.sort((a, b) => a.name.length - b.name.length)[0];
  if (!food) return null;
  if (gram) return { food, qty: Number(gram[1]) / food.servingGrams };
  if (count) return { food, qty: Math.max(0.25, Number(count[1])) };
  return { food, qty: 1 };
}
